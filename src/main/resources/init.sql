CREATE TABLE IF NOT EXISTS measurement_unit (
  code VARCHAR(20) PRIMARY KEY,
  symbol VARCHAR(10) NOT NULL
);
CREATE TABLE IF NOT EXISTS unit_localization (
  unit_code VARCHAR(20) NOT NULL REFERENCES measurement_unit(code),
  language_tag VARCHAR(10) NOT NULL,
  unit_name VARCHAR(80) NOT NULL,
  description VARCHAR(255) NOT NULL,
  PRIMARY KEY(unit_code, language_tag)
);
CREATE TABLE IF NOT EXISTS conversion_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  input_value DOUBLE PRECISION NOT NULL,
  from_unit VARCHAR(20) NOT NULL,
  to_unit VARCHAR(20) NOT NULL,
  result_value DOUBLE PRECISION NOT NULL,
  language_tag VARCHAR(10) NOT NULL,
  converted_at TIMESTAMP WITH TIME ZONE NOT NULL
);
